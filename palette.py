def rgb_to_hex(rgb: Tuple[int, int, int]) -> str:
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def color_dist(r1: int, g1: int, b1: int, r2: int, g2: int, b2: int) -> int:
    """感知加权色差（绿 > 蓝 > 红）。"""
    dr = r1 - r2
    dg = g1 - g2
    db = b1 - b2
    return 2 * dr * dr + 4 * dg * dg + 3 * db * db


def find_nearest_idx(rgb: Tuple[int, int, int]) -> int:
    """返回原始逻辑色表 X01~X38 中最近颜色的索引。"""
    r, g, b = rgb
    return min(
        range(len(EXHIBITION_PALETTE)),
        key=lambda i: color_dist(r, g, b, *EXHIBITION_PALETTE[i][1]),
    )


def find_nearest(rgb: Tuple[int, int, int]) -> Tuple[str, Tuple[int, int, int], str]:
    return EXHIBITION_PALETTE[find_nearest_idx(rgb)]


def logical_to_game_index(logical_idx: int) -> int:
    """将 X01~X38 逻辑索引转换为游戏物理色板格索引（0~39）。"""
    rgb = EXHIBITION_PALETTE[logical_idx][1]
    return min(
        range(len(GAME_PALETTE)),
        key=lambda i: color_dist(*rgb, *GAME_PALETTE[i]),
    )
